/** 그 상황의 말 한 마디: { who, say } */
export function voice(s: VoiceSituation, rng: Rng): { who: string; say: string } {
  const v = LINES[s];
  return { who: v.who, say: v.say[rng.int(v.say.length)] };
}

/** 기사 본문에 붙일 인용: ' 구단 관계자는 "…"라고 말했다.' */
export function quoteLine(s: VoiceSituation, rng: Rng, team?: string): string {
  const v = voice(s, rng);
  const who = v.who === '단장' && team ? `${team} 단장` : v.who;
  return ` ${josa(who, '은', '는')} "${v.say}"라고 말했다.`;
}
