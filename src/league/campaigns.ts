/** 한 시즌의 우리 구단 결과 (결산 때 남긴다) */
export interface SeasonMark {
  year: number;
  /** 정규시즌 순위 (1부터) */
  rank: number;
  teams: number;
  pct: number;
  ps: boolean;
  ks: boolean;
  champ: boolean;
  /** 자체 육성 주전 수 */
  home: number;
  /** 정규시즌 승수 (예전 저장에는 없다) */
  w?: number;
  /** 전기 또는 후기 1위 (시즌을 일정 절반으로 나눈 반기 승률 1위). 예전 저장에는 없다 */
  half?: boolean;
}

export type Metric =
  | { k: 'champ' } | { k: 'ks' } | { k: 'ps' } | { k: 'notLast' }
  | { k: 'rank'; n: number } | { k: 'pct'; v: number } | { k: 'home'; n: number }
  /** 정규시즌 n승 이상 */
  | { k: 'wins'; n: number }
  /** 전기 또는 후기 1위 (1982~1988년 전·후기리그. 게임은 한 시즌을 일정 절반으로 나눠 판정하고, 가을야구는 지금 방식 그대로다) */
  | { k: 'half' };

export type Cond =
  /** 그 해에 */
  | { t: 'in'; year: number; m: Metric }
  /** 시작부터 그 해까지 한 번이라도 */
  | { t: 'by'; year: number; m: Metric }
  /** 기간 중 n번 이상 */
  | { t: 'count'; from: number; to: number; m: Metric; n: number }
  /** 기간 내내 */
  | { t: 'all'; from: number; to: number; m: Metric }
  /** 기간 중 한 시즌에 모두 */
  | { t: 'same'; from: number; to: number; ms: Metric[] };

export interface Stage {
  label: string;
  conds: Cond[];
}

export type Tier = '하' | '중' | '상' | '장기' | '클래식' | '쉬움' | '중간' | '어려움';
