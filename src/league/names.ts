function weighted<T>(list: [T, number][], rng: Rng): T {
  const total = list.reduce((s, [, w]) => s + w, 0);
  let u = rng.next() * total;
  for (const [v, w] of list) if ((u -= w) < 0) return v;
  return list[list.length - 1][0];
}

const pick = <T>(arr: T[], rng: Rng): T => arr[rng.int(arr.length)];

/** 국내 가상 선수 이름. taken에 있는 이름(실존 선수 전원 + 이미 쓴 이름)은 피한다 */
export function koreanName(rng: Rng, taken: Set<string>): string {
  for (let i = 0; i < 200; i++) {
    const n = weighted(SURNAMES, rng) + pick(GIVEN_1, rng) + pick(GIVEN_2, rng);
    if (!taken.has(n)) {
      taken.add(n);
      return n;
    }
  }
  throw new Error('가상 선수 이름을 만들지 못했습니다');
}

/** 외국인 가상 선수 이름. KBO 표기처럼 성만 쓰고, 겹치면 이름까지 붙인다 */
export function foreignName(rng: Rng, taken: Set<string>, asia: boolean): string {
  for (let i = 0; i < 200; i++) {
    const sur = asia ? pick(ASIA_NAMES, rng) : pick(WEST_SUR, rng);
    const candidates = [sur, `${pick(asia ? ASIA_GIVEN : WEST_GIVEN, rng)} ${sur}`];
    for (const n of candidates) {
      if (!taken.has(n)) {
        taken.add(n);
        return n;
      }
    }
  }
  throw new Error('가상 외국인 이름을 만들지 못했습니다');
}
