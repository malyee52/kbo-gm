// 기여(런)를 20~80 등급으로 (잠재력·종합 능력 표시용, 임시 환산).
// 15런(리그 평균 주전) = 50, 1런마다 0.45 (약 22런마다 10). 능력치 등급(display.ts)과 달리 리그 분포가 아니라 고정 환산이다.
// 2026-10-12 사용자 요청으로 폭을 넓혔다: 예전(15런마다 10)에는 60런 이상이 모두 80이라 해마다 상위 4~6명이 같은 등급이었다.
// 지금은 리그 1위(70~75런)가 75~77, 10위(약 55런) 68, 30위(약 40런) 61, 100위(약 20런) 52 정도이고 80은 약 82런이다.
export const GRADE_PER_RUN = 0.45;

export function runsGrade(runs: number): number {
  return Math.max(20, Math.min(80, Math.round(50 + (runs - 15) * GRADE_PER_RUN)));
}
